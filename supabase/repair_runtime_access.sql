-- Repair script for runtime PostgREST 400 issues in team_run_challenge.
-- Run in Supabase SQL Editor as project owner.

begin;

-- Do not keep large photos in Auth metadata: they are copied into every JWT
-- and can make authenticated Data API requests fail at the gateway.
update auth.users
set raw_user_meta_data = raw_user_meta_data - 'avatar_base64'
where raw_user_meta_data ? 'avatar_base64';

-- Ensure base tables exist (safe no-op when they already exist).
create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  name text not null unique,
  km double precision not null default 0,
  originator_id uuid references auth.users(id) on delete set null
);

create table if not exists public.challenges (
  id bigint generated by default as identity primary key,
  name text not null,
  start_date timestamptz not null default now(),
  distance double precision not null,
  team_names text not null default '',
  is_active boolean not null default true,
  end_date timestamptz,
  winner_team text,
  originator_id uuid references auth.users(id) on delete set null
);

create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  team_name text not null,
  runner_name text not null,
  km double precision not null,
  created_at timestamptz not null default now(),
  start_time timestamptz,
  end_time timestamptz
);

-- Ensure required columns exist even in partially migrated databases.
alter table public.challenges add column if not exists team_names text not null default '';
alter table public.challenges add column if not exists is_active boolean not null default true;
alter table public.challenges add column if not exists end_date timestamptz;
alter table public.challenges add column if not exists winner_team text;
alter table public.challenges add column if not exists originator_id uuid references auth.users(id) on delete set null;
alter table public.activities add column if not exists team_name text;
alter table public.activities add column if not exists runner_name text;
alter table public.activities add column if not exists km double precision;
alter table public.activities add column if not exists created_at timestamptz default now();
alter table public.activities add column if not exists start_time timestamptz;
alter table public.activities add column if not exists end_time timestamptz;
alter table public.teams add column if not exists km double precision not null default 0;
alter table public.teams add column if not exists originator_id uuid references auth.users(id) on delete set null;

-- Existing databases may have an id column without an identity/default.
-- Inserts from the app omit id, so generate it from the current maximum.
do $$
declare
  id_is_identity text;
  id_default text;
begin
  select is_identity, column_default
    into id_is_identity, id_default
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'activities'
    and column_name = 'id';

  if coalesce(id_is_identity, 'NO') <> 'YES' and id_default is null then
    create sequence if not exists public.activities_id_seq;
    perform setval(
      'public.activities_id_seq',
      coalesce((select max(id) from public.activities), 0) + 1,
      false
    );
    alter table public.activities
      alter column id set default nextval('public.activities_id_seq');
  end if;
end $$;

create index if not exists teams_originator_id_idx on public.teams(originator_id);
create index if not exists challenges_originator_id_idx on public.challenges(originator_id);

-- Grant table access to API roles.
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.teams to authenticated;
grant select, insert, update, delete on public.challenges to authenticated;
grant select, insert, update, delete on public.activities to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Allow identity inserts for API roles.
grant usage, select on all sequences in schema public to authenticated;

-- Keep anon role read-only where useful for initial screens/auth flows.
grant select on public.teams to anon;
grant select on public.challenges to anon;

-- RLS and permissive policies for current app behavior.
alter table public.teams enable row level security;
alter table public.challenges enable row level security;
alter table public.activities enable row level security;

drop policy if exists "teams read" on public.teams;
create policy "teams read"
on public.teams
for select
to authenticated
using (true);

drop policy if exists "teams write" on public.teams;
create policy "teams write"
on public.teams
for all
to authenticated
using (true)
with check (true);

drop policy if exists "challenges read" on public.challenges;
create policy "challenges read"
on public.challenges
for select
to authenticated
using (true);

drop policy if exists "challenges write" on public.challenges;
create policy "challenges write"
on public.challenges
for all
to authenticated
using (true)
with check (true);

-- Remove unknown old policies too, including restrictive policies that would
-- otherwise continue blocking inserts despite the permissive policy below.
do $$
declare
  p record;
begin
  for p in
    select policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = 'activities'
  loop
    execute format('drop policy if exists %I on public.activities', p.policyname);
  end loop;
end $$;

create policy "activities read"
on public.activities
for select
to authenticated
using (true);

create policy "activities write"
on public.activities
for all
to authenticated
using (true)
with check (true);

commit;

-- Refresh PostgREST after changing an existing table or its policies.
notify pgrst, 'reload schema';

